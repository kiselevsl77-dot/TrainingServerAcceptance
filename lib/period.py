"""Границы периода для серверных фильтров даты-времени.

`GET /api/tasks/` принимает `start_date`/`end_date` только как дату-время
(спецификация `SOM1.json`: `string`/`format: date-time`). Строка из одной даты
`2026-09-09` отклоняется статусом 422 с текстом «invalid datetime separator,
expected `T`, `t`, `_` or space» — проверено на живом стенде 16.09.2026, тот же
ответ виден в журнале пульта. Поэтому сутки переводятся в границы с явным
временем, а незаданная граница возвращается пустой строкой (клиент такие
фильтры отбрасывает, `client.tasks._drop_empty`).

Верхняя граница отдаётся **началом следующих суток**: на сервере `end_date`
сравнивается как исключающая (`created_at < end_date`), поэтому только так
выбранный день попадает в выборку целиком. Нижняя граница (`start_date`)
включающая, но на ней обнаружен артефакт ±1 с: задача, созданная за 0,5 с до
границы, всё ещё попадает в выборку — для фильтров по суткам это не важно.

Наивные значения сравниваются с наивными UTC-отметками задач: `…T00:00:00Z` и
`…T00:00:00+03:00` дают ту же выборку суток, что и `<день>T00:00:00`, поэтому
период считается по тем же значениям, которые показаны в таблице задач.
"""

from __future__ import annotations

from datetime import date, datetime, time, timedelta

#: Начало суток — нижняя граница периода.
DAY_START = time.min


def date_time_bound(day: date | None, *, days: int = 0) -> str:
    """Граница периода как строка `date-time`: `<день + days>T00:00:00`.

    Для незаданного дня (или значения не-даты, например `None` из очищенного
    поля `st.date_input`) возвращается пустая строка — фильтр не отправляется.
    """
    if not isinstance(day, date):
        return ""
    return datetime.combine(day + timedelta(days=days), DAY_START).isoformat()


def day_bounds(start: date | None, end: date | None) -> tuple[str, str]:
    """Границы периода суток для query-параметров `start_date`/`end_date`.

    Возвращает `(start_date, end_date)`: начало выбранного дня и начало суток,
    следующих за выбранным концом периода (серверная граница исключающая).

        >>> day_bounds(date(2026, 9, 9), date(2026, 9, 16))
        ('2026-09-09T00:00:00', '2026-09-17T00:00:00')
        >>> day_bounds(None, None)
        ('', '')
    """
    return date_time_bound(start), date_time_bound(end, days=1)
