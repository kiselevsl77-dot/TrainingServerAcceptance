"""Компоненты интерфейса пульта: то, что повторяется на разных экранах.

Этап 2 дал каркас экрана (`screen`), этап 3 наполняет экраны и выносит общие куски
интерфейса сюда, чтобы они не переписывались в каждом экране:

* `layout` — шапка экрана, две зоны макета (рабочая область и панель контекста),
  KPI, таблицы и состояние «нет сессии»;
* `status` — подписи и пиктограммы статусов проверок, маркеров очереди и классов
  проверок: единый словарь, поэтому одинаковые вещи выглядят одинаково;
* `journal` — лента обмена (запрос и ответ раздельно) для `SCR-301`, `SCR-302`, `SCR-402`;
* `run_card` — карточка запуска изменяющих и ресурсоёмких проверок (`FR-P-19`);
* `flash` — короткие сообщения экрана: результат действия виден после перерисовки.

Соглашение: логика отбора и форматирования живёт в **чистых** функциях модуля, а
рисующие функции только собирают из них разметку. Поэтому поведение проверяется
unit-тестами (`tests/unit/test_ui_components.py`), а не только смоуком.
"""

