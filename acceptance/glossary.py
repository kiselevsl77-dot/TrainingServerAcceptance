    """Термин глоссария: каноническая подпись, принадлежность и значение."""

    key: str
    title: str
    scope: str
    meaning: str

    @property
    def is_server(self) -> bool:
        """True, если термин обозначает сущность испытываемого сервера."""
        return self.scope == SCOPE_SERVER


