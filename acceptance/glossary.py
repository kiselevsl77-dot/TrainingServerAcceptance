TERMS: dict[str, Term] = {term.key: term for term in _TERMS}


def term(key: str) -> str:
    """Каноническая подпись термина по ключу (KeyError — если ключа нет).

    Используется в подписях интерфейса, чтобы «$Задачи», «$Датасеты» и другие
    сущности стенда назывались одинаково во всех экранах и документах.
    """
    return TERMS[key].title


def find(key: str) -> Term | None:
    """Термин по ключу или None (для тестов и подсказок)."""
    return TERMS.get(key)


def terms(*, scope: str | None = None) -> tuple[Term, ...]:
    """Все термины (при необходимости — только указанной принадлежности)."""
    if scope is None:
        return _TERMS
    return tuple(item for item in _TERMS if item.scope == scope)


def server_terms() -> tuple[Term, ...]:
    """Термины испытываемого сервера (все — с префиксом `$`)."""
    return terms(scope=SCOPE_SERVER)


def pult_terms() -> tuple[Term, ...]:
    """Внутренние термины пульта (без префикса)."""
    return terms(scope=SCOPE_PULT)


def is_server_label(label: str) -> bool:
    """True, если подпись начинается с префиксом сущностей стенда."""
    return str(label).strip().startswith(SERVER_PREFIX)


