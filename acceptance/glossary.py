"""Глоссарий пульта: сущности испытуемого стенда против внутренних сущностей пульта.

Пожелание заказчика (21.09.2026, п. 4): термины, относящиеся к **испытываемому
серверу**, и внутренние термины пульта должны быть различимы в текстах
документации и в интерфейсе. Правило одно и оно механическое:

    * сущности **стенда** (приходят и уходят по API) — с префиксом ``$``:
      ``$Задача``, ``$Файл``, ``$Датасет``, ``$Модель``, ``$Нагрузка``;
    * внутренние сущности **пульта** (их создаёт сам пульт для испытаний) —
      без префикса: ``проверка``, ``карточка проверки``, ``карточка запуска``,
      ``программа испытаний``, ``запись``, ``замечание к API``, ``артефакт``.

Отдельно разводятся три «программы», которые раньше назывались одинаково:

    * **программа испытаний** (``program``) — план вызовов: что и в каком порядке
      исполняет пульт (экран «Монитор обмена», сессия);
    * **программа проверок** (``checklist``) — документ ``docs/02`` и каталог
      ``TC-*`` (состав проверок и правила их выполнения);
    * **программа-методика** (``program_doc``) — документ заказчика, реквизиты
      которого вносятся в сессию (``SessionInfo.program_doc``).

Модуль — единственный источник канонических подписей: экранные заголовки
(``acceptance/app.py``) и страницы берут подписи отсюда, а соответствие глоссария
таблице руководства (`docs/12` §1.4) проверяет ``tests/unit/test_glossary.py``.
"""

