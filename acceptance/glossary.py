#: Префикс сущностей испытуемого сервера.
SERVER_PREFIX = "$"

#: Принадлежность термина: сущность стенда (испытуемого сервера) или пульта.
SCOPE_SERVER = "стенд (сервер)"
SCOPE_PULT = "пульт"


